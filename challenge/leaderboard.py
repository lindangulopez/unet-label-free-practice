"""Check every submission and rebuild LEADERBOARD.md.

Usage: python challenge/leaderboard.py          # check and write LEADERBOARD.md
       python challenge/leaderboard.py --check  # check only (used on pull requests)

Ranking: for each metric (MAE lower is better; SSIM and PCC higher is better), teams are
ranked on their mean over the test images; the final score is the mean of the three ranks.
Ties are broken by PCC, then by submission date.
"""
import argparse
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
CONFIG = json.loads((ROOT / "challenge" / "config.json").read_text())
REQUIRED = ["team", "method", "date", "code_url", "licence"]
BADGES = {"swhid": "archived", "codemeta": "described", "rerun": "re-run"}


def load(sub):
    meta = json.loads((sub / "submission.json").read_text())
    for key in REQUIRED:
        if not meta.get(key):
            raise ValueError(f"{sub.name}: submission.json has no '{key}'")
    scores = pd.read_csv(sub / "scores.csv")
    expected = set(CONFIG["test_set_ids"])
    got = set(scores["set_id"])
    if got != expected:
        raise ValueError(f"{sub.name}: scores.csv covers sets {sorted(got)}, expected {sorted(expected)}")
    means = scores[["MAE", "SSIM", "PCC"]].mean()
    badges = [label for key, label in BADGES.items() if meta.get(key)]
    return {"team": meta["team"], "method": meta["method"], "date": meta["date"],
            "code": meta["code_url"], **means.to_dict(), "badges": ", ".join(badges) or "-"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows, errors = [], []
    for sub in sorted(p for p in (ROOT / "submissions").iterdir() if p.is_dir() and p.name != "TEMPLATE"):
        try:
            rows.append(load(sub))
        except (ValueError, FileNotFoundError, KeyError) as e:
            errors.append(str(e))
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    print(f"{len(rows)} submissions OK")
    if args.check or not rows:
        return

    board = pd.DataFrame(rows)
    board["rank_MAE"] = board["MAE"].rank(method="min")
    board["rank_SSIM"] = board["SSIM"].rank(ascending=False, method="min")
    board["rank_PCC"] = board["PCC"].rank(ascending=False, method="min")
    board["score"] = board[["rank_MAE", "rank_SSIM", "rank_PCC"]].mean(axis=1)
    board = board.sort_values(["score", "PCC", "date"], ascending=[True, False, True]).reset_index(drop=True)
    board.insert(0, "#", board.index + 1)
    board["code"] = "[link](" + board["code"] + ")"
    cols = ["#", "team", "method", "score", "MAE", "SSIM", "PCC", "badges", "code", "date"]

    lines = ["# Leaderboard", "",
             f"Task: {CONFIG['task']}. Test data: {CONFIG['test_data']}. "
             "Score = mean of the ranks on MAE, SSIM and PCC (lower is better). Generated by `challenge/leaderboard.py`.", "",
             board[cols].round(3).to_markdown(index=False), ""]
    (ROOT / "LEADERBOARD.md").write_text("\n".join(lines))
    print("LEADERBOARD.md written")


if __name__ == "__main__":
    main()
